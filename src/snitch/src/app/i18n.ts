export type TranslationKey = Key

export const language = computed<'de' | 'en'>(() =>
  phoneContext.language.toLowerCase().startsWith('de') ? 'de' : 'en',
)

export const locale = computed(() => (language.value === 'de' ? 'de-DE' : 'en-US'))

export function t(key: Key, params: Record<string, string | number> = {}): string {
  const table = language.value === 'de' ? de : en
  return table[key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ''))
}

/** Localized text for a server error code. */
export function errorText(code: string | undefined): string {
  const key = `error.${code}` as Key
  return key in de ? t(key) : t('error.generic')
}

export function reasonText(code: string | undefined): string {
  const key = `reason.${code}` as Key
  return key in de ? t(key) : t('reason.ended')
}

export function categoryLabel(label: Record<string, string> | undefined, fallback: string): string {
  if (!label) return fallback
  return label[language.value] ?? label.en ?? label.de ?? fallback
}
